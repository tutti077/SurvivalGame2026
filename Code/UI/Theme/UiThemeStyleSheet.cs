using System.Globalization;
using System.Text;
using Sandbox;
using Sandbox.UI;

namespace Survival;

/// <summary>
/// The class-based side of the theme for razor panels (main menu, load screen) and anything else
/// that prefers classes to inline styles: a stylesheet generated from <see cref="UiTheme.Current"/>
/// and attached to a root with <see cref="Attach"/>. Classes mirror <see cref="UiStyle"/> —
/// <c>ui-backdrop</c>, <c>ui-card</c>, <c>ui-frame</c>, <c>ui-title</c>, <c>ui-header</c>, <c>ui-body</c>,
/// <c>ui-secondary</c>, <c>ui-muted</c>, <c>ui-button</c> (+ <c>primary</c> / <c>danger</c> / <c>ghost</c> /
/// <c>disabled</c>, with hover and active states), <c>ui-field</c>, <c>ui-row</c> (+ <c>selected</c>),
/// <c>ui-bar-track</c> / <c>ui-bar-fill</c>, <c>ui-divider</c>. Layout stays in the panel's own SCSS.
/// </summary>
public static class UiThemeStyleSheet
{
	const string SheetKeyPrefix = "ui_theme_";

	/// <summary>
	/// The sheet for the current theme. Built on every read (a few kB of string work, once per
	/// root attach): a static cache here survived the editor's hotload and kept serving a sheet
	/// generated by the previous code.
	/// </summary>
	public static string Css => Build( UiTheme.Current );

	/// <summary>Attach (or re-attach after a theme change) the generated sheet to <paramref name="root"/>.</summary>
	public static void Attach( Panel root )
	{
		if ( root is null || !root.IsValid() )
			return;

		// The engine caches inline sheets by key across hotloads, so the key carries a hash of the
		// CSS itself: a regenerated sheet (theme edit, code change) never reuses a stale cached copy.
		var css = Css;
		root.StyleSheet.Remove( SheetKeyPrefix + "*" );
		root.StyleSheet.AddInline( css, SheetKeyPrefix + UiTheme.Current.Id + "_" + ContentHash( css ) );
	}

	/// <summary>FNV-1a over the sheet text — stable across processes, unlike string.GetHashCode.</summary>
	static string ContentHash( string text )
	{
		unchecked
		{
			uint hash = 2166136261;
			for ( var i = 0; i < text.Length; i++ )
				hash = (hash ^ text[i]) * 16777619;
			return hash.ToString( "x8", CultureInfo.InvariantCulture );
		}
	}

	static string Build( UiThemeData t )
	{
		var c = t.Colors;
		var m = t.Metrics;
		var f = t.Fonts;
		var sb = new StringBuilder( 6000 );
		var inv = CultureInfo.InvariantCulture;

		string Px( float v ) => v.ToString( "0.##", inv ) + "px";
		string Rgba( Color col ) => UiStyle.Css( col );
		var shadow = $"{m.Shadow} {Rgba( c.ShadowColor )}";
		var textShadow = $"0px 1px 2px {Rgba( c.TextShadowColor )}";
		var headingTransform = f.HeadingUppercase ? "uppercase" : "none";

		sb.Append( ".ui-backdrop { background-color: " ).Append( Rgba( c.BackdropColor ) ).Append( ';' );
		if ( !string.IsNullOrWhiteSpace( t.Textures.Vignette ) )
			sb.Append( " background-image: url( " ).Append( t.Textures.Vignette ).Append( " ); background-size: 100% 100%; background-repeat: no-repeat;" );
		if ( m.BackdropBlur > 0f )
			sb.Append( " backdrop-filter: blur( " ).Append( Px( m.BackdropBlur ) ).Append( " );" );
		sb.Append( " }\n" );

		sb.Append( ".ui-card { background-color: " ).Append( Rgba( c.PanelColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderColor ) )
			.Append( "; border-radius: " ).Append( Px( m.RadiusLarge ) )
			.Append( "; box-shadow: " ).Append( shadow ).Append( "; }\n" );

		sb.Append( ".ui-frame { background-color: " ).Append( Rgba( c.PanelColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidthStrong ) ).Append( " solid " ).Append( Rgba( c.BorderStrongColor ) )
			.Append( "; border-radius: " ).Append( Px( m.RadiusLarge ) )
			.Append( "; box-shadow: " ).Append( shadow ).Append( "; }\n" );

		sb.Append( ".ui-raised { background-color: " ).Append( Rgba( c.PanelRaisedColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderSubtleColor ) )
			.Append( "; border-radius: " ).Append( Px( m.Radius ) ).Append( "; }\n" );

		sb.Append( ".ui-sunken { background-color: " ).Append( Rgba( c.PanelSunkenColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderSubtleColor ) )
			.Append( "; border-radius: " ).Append( Px( m.Radius ) ).Append( "; }\n" );

		sb.Append( ".ui-title { font-family: " ).Append( f.Heading ).Append( "; font-weight: " ).Append( f.HeadingWeight )
			.Append( "; font-size: " ).Append( Px( m.FontTitle ) ).Append( "; color: " ).Append( Rgba( c.TextPrimaryColor ) )
			.Append( "; letter-spacing: " ).Append( Px( f.HeadingLetterSpacing ) ).Append( "; text-transform: " ).Append( headingTransform )
			.Append( "; text-shadow: " ).Append( textShadow ).Append( "; }\n" );

		sb.Append( ".ui-header { font-family: " ).Append( f.Heading ).Append( "; font-weight: " ).Append( f.HeadingWeight )
			.Append( "; font-size: " ).Append( Px( m.FontHeader ) ).Append( "; color: " ).Append( Rgba( c.AccentColor ) )
			.Append( "; letter-spacing: " ).Append( Px( f.HeadingLetterSpacing * 0.6f ) ).Append( "; text-transform: " ).Append( headingTransform ).Append( "; }\n" );

		sb.Append( ".ui-body { font-family: " ).Append( f.Body ).Append( "; font-weight: " ).Append( f.BodyWeight )
			.Append( "; font-size: " ).Append( Px( m.FontBody ) ).Append( "; color: " ).Append( Rgba( c.TextPrimaryColor ) ).Append( "; }\n" );

		sb.Append( ".ui-secondary { font-family: " ).Append( f.Body ).Append( "; font-weight: " ).Append( f.BodyWeight )
			.Append( "; font-size: " ).Append( Px( m.FontSmall ) ).Append( "; color: " ).Append( Rgba( c.TextSecondaryColor ) ).Append( "; }\n" );

		sb.Append( ".ui-muted { font-family: " ).Append( f.Body ).Append( "; font-weight: " ).Append( f.BodyWeight )
			.Append( "; font-size: " ).Append( Px( m.FontSmall ) ).Append( "; color: " ).Append( Rgba( c.TextMutedColor ) ).Append( "; }\n" );

		sb.Append( ".ui-value { font-family: " ).Append( f.Body ).Append( "; font-weight: " ).Append( f.ValueWeight )
			.Append( "; font-size: " ).Append( Px( m.FontBody ) ).Append( "; color: " ).Append( Rgba( c.TextPrimaryColor ) ).Append( "; }\n" );

		sb.Append( ".ui-accent { color: " ).Append( Rgba( c.AccentBrightColor ) ).Append( "; }\n" );

		// Buttons: rest / hover / active / disabled, four kinds.
		sb.Append( ".ui-button { font-family: " ).Append( f.Body ).Append( "; font-weight: " ).Append( f.ValueWeight )
			.Append( "; font-size: " ).Append( Px( m.FontBody ) ).Append( "; color: " ).Append( Rgba( c.TextPrimaryColor ) )
			.Append( "; background-color: " ).Append( Rgba( c.ButtonColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.ButtonBorderColor ) )
			.Append( "; border-radius: " ).Append( Px( m.Radius ) )
			.Append( "; align-items: center; justify-content: center; text-align: center; cursor: pointer; transition: background-color 0.08s ease-out, border-color 0.08s ease-out; }\n" );
		sb.Append( ".ui-button:hover { background-color: " ).Append( Rgba( c.ButtonHoverColor ) )
			.Append( "; border-color: " ).Append( Rgba( c.BorderStrongColor ) )
			.Append( "; box-shadow: 0px 0px 10px " ).Append( Rgba( c.AccentGlowColor ) ).Append( "; }\n" );
		sb.Append( ".ui-button:active { background-color: " ).Append( Rgba( c.ButtonPressedColor ) ).Append( "; box-shadow: none; }\n" );

		sb.Append( ".ui-button.primary { background-color: " ).Append( Rgba( c.ButtonPrimaryColor ) )
			.Append( "; border-color: " ).Append( Rgba( c.ButtonPrimaryBorderColor ) ).Append( "; }\n" );
		sb.Append( ".ui-button.primary:hover { background-color: " ).Append( Rgba( c.ButtonPrimaryHoverColor ) ).Append( "; }\n" );
		sb.Append( ".ui-button.primary:active { background-color: " ).Append( Rgba( c.ButtonPrimaryPressedColor ) ).Append( "; }\n" );

		sb.Append( ".ui-button.danger { background-color: " ).Append( Rgba( c.ButtonDangerColor ) )
			.Append( "; border-color: " ).Append( Rgba( c.ButtonDangerBorderColor ) ).Append( "; }\n" );
		sb.Append( ".ui-button.danger:hover { background-color: " ).Append( Rgba( c.ButtonDangerHoverColor ) ).Append( "; }\n" );

		sb.Append( ".ui-button.ghost { background-color: transparent; border-color: " ).Append( Rgba( c.BorderSubtleColor ) ).Append( "; }\n" );
		sb.Append( ".ui-button.ghost:hover { background-color: " ).Append( Rgba( c.ButtonHoverColor ) ).Append( "; }\n" );

		sb.Append( ".ui-button.disabled { opacity: 0.45; pointer-events: none; }\n" );

		// Text entry.
		sb.Append( ".ui-field { font-family: " ).Append( f.Body ).Append( "; font-size: " ).Append( Px( m.FontBody ) )
			.Append( "; color: " ).Append( Rgba( c.TextPrimaryColor ) )
			.Append( "; background-color: " ).Append( Rgba( c.PanelSunkenColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderColor ) )
			.Append( "; border-radius: " ).Append( Px( m.RadiusSmall ) ).Append( "; }\n" );
		sb.Append( ".ui-field:focus { border-color: " ).Append( Rgba( c.AccentColor ) ).Append( "; }\n" );

		// Selectable list rows.
		sb.Append( ".ui-row { background-color: " ).Append( Rgba( c.PanelRaisedColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderSubtleColor ) )
			.Append( "; border-radius: " ).Append( Px( m.Radius ) ).Append( "; cursor: pointer; }\n" );
		sb.Append( ".ui-row:hover { border-color: " ).Append( Rgba( c.BorderStrongColor ) ).Append( "; }\n" );
		sb.Append( ".ui-row.selected { background-color: " ).Append( Rgba( c.TabSelectedColor ) )
			.Append( "; border-color: " ).Append( Rgba( c.AccentColor ) )
			.Append( "; box-shadow: 0px 0px 10px " ).Append( Rgba( c.AccentGlowColor ) ).Append( "; }\n" );

		// Bars.
		sb.Append( ".ui-bar-track { background-color: " ).Append( Rgba( c.BarTrackColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BarBorderColor ) )
			.Append( "; border-radius: " ).Append( Px( m.RadiusSmall ) ).Append( "; overflow: hidden; }\n" );
		sb.Append( ".ui-bar-fill { background-color: " ).Append( Rgba( c.AccentColor ) ).Append( "; }\n" );

		// Divider.
		sb.Append( ".ui-divider { height: 1px; width: 100%; background-color: " ).Append( Rgba( c.DividerColor ) ).Append( ';' );
		if ( !string.IsNullOrWhiteSpace( t.Textures.Divider ) )
			sb.Append( " background-color: transparent; background-image: url( " ).Append( t.Textures.Divider )
				.Append( " ); background-size: 100% 100%; background-repeat: no-repeat; background-tint: " ).Append( Rgba( c.AccentColor ) ).Append( ';' );
		sb.Append( " }\n" );

		// Corner brackets for a razor .ui-frame: four <div class="ui-corner tl|tr|br|bl"> inside the frame.
		if ( !string.IsNullOrWhiteSpace( t.Textures.CornerOrnament ) )
		{
			var inset = Px( -m.BorderWidthStrong );
			sb.Append( ".ui-corner { position: absolute; width: " ).Append( Px( m.CornerOrnament ) ).Append( "; height: " ).Append( Px( m.CornerOrnament ) )
				.Append( "; pointer-events: none; z-index: 5; background-image: url( " ).Append( t.Textures.CornerOrnament )
				.Append( " ); background-size: contain; background-repeat: no-repeat; image-rendering: pixelated; background-tint: " ).Append( Rgba( c.AccentColor ) ).Append( "; }\n" );
			sb.Append( ".ui-corner.tl { left: " ).Append( inset ).Append( "; top: " ).Append( inset ).Append( "; }\n" );
			sb.Append( ".ui-corner.tr { right: " ).Append( inset ).Append( "; top: " ).Append( inset ).Append( "; transform: rotate( 90deg ); }\n" );
			sb.Append( ".ui-corner.br { right: " ).Append( inset ).Append( "; bottom: " ).Append( inset ).Append( "; transform: rotate( 180deg ); }\n" );
			sb.Append( ".ui-corner.bl { left: " ).Append( inset ).Append( "; bottom: " ).Append( inset ).Append( "; transform: rotate( 270deg ); }\n" );
		}

		sb.Append( ".ui-keycap { background-color: " ).Append( Rgba( c.KeyCapColor ) ).Append( "; color: " ).Append( Rgba( c.KeyCapTextColor ) )
			.Append( "; border: " ).Append( Px( m.BorderWidth ) ).Append( " solid " ).Append( Rgba( c.BorderStrongColor ) )
			.Append( "; border-radius: " ).Append( Px( m.RadiusSmall ) ).Append( "; }\n" );

		return sb.ToString();
	}
}
