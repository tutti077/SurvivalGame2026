"""Writers: Wavefront OBJ (Y-up, Blender export convention), the s&box .vmdl beside it, the pixel_lit
.vmat and the 256 px texture. One folder per item: Assets/models/<category>/<name>/<name>.{obj,vmdl,png,vmat}.

OBJ carries no unit or axis, so the file is written the way Blender's exporter does by default
(forward -Z, up Y: engine (x, y, z) -> obj (x, z, -y)) and the vmdl applies import_scale 40
(metres -> 40 units per metre, CLAUDE.md commandment 5).
"""
import os
import numpy as np

from . import texture

IMPORT_SCALE = 40.0   # OBJ is in metres


def write_obj(path, mesh, name):
	tris = mesh.tris
	uv = mesh.uv
	n = mesh.normals()
	lines = [f"# {name} - generated by Tools/item_models (metres authored Z-up, written Y-up)", f"o {name}", f"g {name}",
			 f"usemtl {name}", "s off"]
	verts = []
	for t in tris.reshape(-1, 3):
		verts.append(f"v {t[0]:.5f} {t[2]:.5f} {-t[1]:.5f}")
	uvs = [f"vt {u[0]:.5f} {u[1]:.5f}" for u in uv.reshape(-1, 2)]
	nrm = [f"vn {v[0]:.4f} {v[2]:.4f} {-v[1]:.4f}" for v in n]
	faces = []
	for i in range(len(tris)):
		a = 3 * i + 1
		faces.append(f"f {a}/{a}/{i + 1} {a + 1}/{a + 1}/{i + 1} {a + 2}/{a + 2}/{i + 1}")
	with open(path, "w", newline="\n") as f:
		f.write("\n".join(lines + verts + uvs + nrm + faces) + "\n")


